"""Host 侧记忆接口契约（Port / Protocol）。

这里定义的是 **host 唯一依赖** 的接口，而不是依赖 ``simple-harness-memory-sdk``
的具体实现。SDK 上线时由适配层把 SDK 后端接到本契约，host 其余代码不改。

边界（与 ``ARCHITECTURE/MEMORY_SDK_BOUNDARY.md`` 一致）：
- 进 SDK：``MemoryBackend``、``Embedder``、``WorldModelPort``。
- 留 host：ContextSnapshotStore（deskpet.agent）、CompanionMessageProjection
  （deskpet.companion）、coverage 规划（deskpet.agent.context_segment_store）。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol, runtime_checkable


# ── 宿主自有的最小数据模型 ─────────────────────────
# 这些是 host 侧的接口数据形状，刻意不 import SDK 类型，避免反向耦合。

@dataclass
class Message:
    id: int | None
    session_id: str
    role: str
    content: str
    created_at: float = 0.0
    # host 侧会话/工作流/工具调用的溯源元数据，SDK Message 必须能往返这些字段。
    root_run_id: str | None = None
    workflow_event_id: str | None = None
    tool_call_id: str | None = None
    salience: float = 0.0
    decay_rate: float = 0.02
    embedding: bytes | None = None
    is_summary: bool = False
    summary_of: str | None = None


@dataclass
class Fact:
    id: int | None
    subject: str
    key: str
    value: str
    category: str
    confidence: float
    evidence: str
    source_msg_id: int
    created_at: float
    pinned: bool = False
    superseded_by: int | None = None
    forgotten_at: float | None = None

    @property
    def is_active(self) -> bool:
        return self.superseded_by is None and self.forgotten_at is None


@dataclass
class Hit:
    message_id: int
    text: str
    score: float
    source: str
    session_id: str | None = None
    role: str | None = None
    created_at: float | None = None
    session_affinity: float = 1.0


# ── 宿主侧接口契约 ────────────────────────────────

@runtime_checkable
class MemoryBackend(Protocol):
    """记忆后端契约。SDK 后端通过结构类型满足此 Protocol。"""

    async def append_message(
        self,
        session_id: str,
        role: str,
        content: str,
        *,
        workflow_event_id: str | None = None,
        root_run_id: str | None = None,
        tool_call_id: str | None = None,
    ) -> int: ...

    async def get_recent_messages(self, session_id: str, limit: int = 20) -> list[Message]: ...

    async def get_message(self, message_id: int) -> Message | None: ...

    async def recall(
        self,
        query: str,
        session_id: str | None = None,
        limit: int = 10,
    ) -> list[Hit]: ...

    async def vector_search(self, query: str, limit: int = 20) -> list[Hit]: ...

    async def extract_facts(
        self,
        message_id: int,
        content: str,
        role: str,
    ) -> list[Fact]: ...

    async def get_facts(
        self,
        subject: str = "user",
        category: str | None = None,
        active_only: bool = True,
    ) -> list[Fact]: ...

    async def forget_fact(self, fact_id: int, reason: str = "") -> bool: ...

    async def get_digital_twin(self, subject: str = "user") -> Any: ...

    async def update_digital_twin(self, twin: Any) -> None: ...

    async def suggest_questions(self, subject: str = "user") -> list[str]: ...

    async def detect_inconsistencies(self, subject: str = "user") -> list[Any]: ...

    async def daily_decay(self) -> dict[str, int]: ...

    async def summarize_old_sessions(
        self,
        older_than_days: int = 7,
        max_sessions: int = 5,
    ) -> dict[str, int]: ...

    async def record_workspace_action(
        self,
        session_id: str,
        action_type: str,
        payload: dict,
    ) -> None: ...

    async def initialize(self) -> None: ...

    async def close(self) -> None: ...


