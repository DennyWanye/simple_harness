@runtime_checkable
class Embedder(Protocol):
    """host 侧向量化契约。

    注意：host 旧调用是 ``await embedder.encode(texts)`` + ``embedder.is_mock()``。
    SDK 提供的 Embedder 是同步 ``embed``/``embed_batch``，host 适配层负责
    sync→async 包装并补 ``is_mock``。
    """

    @property
    def dim(self) -> int: ...

    def is_mock(self) -> bool: ...

    async def encode(self, texts: list[str]) -> list[list[float]]: ...


